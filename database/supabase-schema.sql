-- Humas Content Hub — skema database untuk Supabase (PostgreSQL)
-- Jalankan di: Supabase Dashboard -> SQL Editor -> New query -> Run
-- Nama database Supabase selalu "postgres" (DB_DATABASE=postgres).
--
-- PENTING: pakai SALAH SATU saja:
--   (A) skrip SQL ini, atau
--   (B) php artisan migrate --seed
-- Jangan dua-duanya (tabel akan bentrok).
-- Jika memakai skrip ini, set SESSION_DRIVER=file di .env (sudah default dari setup.php).
-- ============================================================

-- ---------- users (login) ----------
CREATE TABLE IF NOT EXISTS users (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name              VARCHAR(255) NOT NULL,
    username          VARCHAR(255) UNIQUE,
    email             VARCHAR(255) NOT NULL UNIQUE,
    email_verified_at TIMESTAMP(0),
    password          VARCHAR(255) NOT NULL,
    remember_token    VARCHAR(100),
    created_at        TIMESTAMP(0),
    updated_at        TIMESTAMP(0)
);

-- ---------- konten ----------
CREATE TABLE IF NOT EXISTS contents (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title            VARCHAR(255) NOT NULL,
    type             VARCHAR(255) NOT NULL,
    channels         JSONB        NOT NULL,
    status           VARCHAR(255) NOT NULL DEFAULT 'Belum Dikerjakan',
    requester_name   VARCHAR(255) NOT NULL,
    responsible_name VARCHAR(255) NOT NULL,
    brief            TEXT,
    deadline         DATE         NOT NULL,
    deadline_note    VARCHAR(255) NOT NULL DEFAULT 'Same Day',
    caption          TEXT,
    publish_at       TIMESTAMP(0),
    final_draft_id   BIGINT,
    created_at       TIMESTAMP(0),
    updated_at       TIMESTAMP(0)
);
CREATE INDEX IF NOT EXISTS contents_status_index ON contents (status);

-- ---------- bahan/footage & referensi ----------
CREATE TABLE IF NOT EXISTS content_assets (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content_id  BIGINT       NOT NULL REFERENCES contents(id) ON DELETE CASCADE,
    category    VARCHAR(255) NOT NULL,          -- material | reference
    kind        VARCHAR(255) NOT NULL,          -- file | text | link
    name        VARCHAR(255) NOT NULL,
    text        TEXT,
    path        VARCHAR(255),
    size_label  VARCHAR(255),
    file_type   VARCHAR(255),
    created_at  TIMESTAMP(0),
    updated_at  TIMESTAMP(0)
);
CREATE INDEX IF NOT EXISTS content_assets_content_id_category_index ON content_assets (content_id, category);

-- ---------- draft ----------
CREATE TABLE IF NOT EXISTS drafts (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content_id  BIGINT       NOT NULL REFERENCES contents(id) ON DELETE CASCADE,
    kind        VARCHAR(255) NOT NULL,          -- file | text | link
    name        VARCHAR(255) NOT NULL,
    text        TEXT,
    path        VARCHAR(255),
    size_label  VARCHAR(255),
    file_type   VARCHAR(255),
    created_at  TIMESTAMP(0),
    updated_at  TIMESTAMP(0)
);

-- ---------- komentar draft ----------
CREATE TABLE IF NOT EXISTS draft_comments (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    draft_id    BIGINT       NOT NULL REFERENCES drafts(id) ON DELETE CASCADE,
    user_name   VARCHAR(255) NOT NULL,
    body        TEXT         NOT NULL,
    created_at  TIMESTAMP(0),
    updated_at  TIMESTAMP(0)
);

-- FK final draft (dibuat belakangan karena saling merujuk)
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'contents_final_draft_id_foreign') THEN
        ALTER TABLE contents
            ADD CONSTRAINT contents_final_draft_id_foreign
            FOREIGN KEY (final_draft_id) REFERENCES drafts(id) ON DELETE SET NULL;
    END IF;
END $$;

-- ---------- keamanan: aktifkan RLS ----------
-- Tanpa ini, tabel terbuka lewat Data API (anon key) Supabase.
-- Laravel memakai role postgres yang bypass RLS, jadi aplikasi tetap jalan.
ALTER TABLE users          ENABLE ROW LEVEL SECURITY;
ALTER TABLE contents       ENABLE ROW LEVEL SECURITY;
ALTER TABLE content_assets ENABLE ROW LEVEL SECURITY;
ALTER TABLE drafts         ENABLE ROW LEVEL SECURITY;
ALTER TABLE draft_comments ENABLE ROW LEVEL SECURITY;

